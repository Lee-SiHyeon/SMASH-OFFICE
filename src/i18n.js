export function makeT(lang) {
  const D = STR[lang] || STR.ko;
  const T = (key, ...a) => {
    let v = key.split('.').reduce((o, k) => (o == null ? o : o[k]), D);
    if (v == null) v = key.split('.').reduce((o, k) => (o == null ? o : o[k]), STR.ko);
    return typeof v === 'string' ? v.replace(/\{(\d)\}/g, (_, i) => a[+i] ?? '') : v;
  };
  return T;
}
